func chainTopics() []string {
	out := make([]string, 0, len(chains))
	for k := range chains {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// linkedTurn отдаёт реплику в манере капитана и запасные формулировки того же хода.
func linkedTurn(topic string, step int, style VoiceStyle) []string {
	turns, ok := chains[topic]
	if !ok || step < 0 || step >= len(turns) {
		return nil
	}
	turn := turns[step]
	idx := styleIndex(style)
	out := make([]string, 0, 6)
	for i := 0; i < 6; i++ {
		out = append(out, turn[(idx+i)%6])
	}
	return out
}
