package design

import (
	"fmt"
	"strings"
)

// Prompt возвращает промпт для создания замены элемента (R-54): его копируют из админки и вставляют в ChatGPT или в 3D-редактор-помощник.
// Промпт содержит назначение элемента, технические требования формата и ограничения (права, размер, безопасность).
func (s *Service) Prompt(elementID string) (string, error) {
	el, ok := s.catalog.Get(elementID)
	if !ok {
		return "", ErrNoElement
	}
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	w("Ты — художник и технический художник мобильной космической MMORPG «Звёздные рубежи» (Godot 4, Android, вид сверху-сбоку).")
	w("Нужно создать замену элемента дизайна. Ниже — что это за элемент, что именно сделать и как проверить результат.")
	w("")
	w("ЭЛЕМЕНТ: %s", el.Name)
	w("Ключ в админке: %s · группа: «%s»", el.ID, el.Group)
	if len(el.UsedBy) > 0 {
		w("Где используется: %s", strings.Join(el.UsedBy, ", "))
	}
	w("")
	switch el.Category {
	case CatModel:
		modelPrompt(&b, el)
	case CatIcon:
		iconPrompt(&b, el)
	case CatBackground:
		backgroundPrompt(&b, el)
	case CatShipData:
		shipDataPrompt(&b, el)
	}
	w("")
	w("ОБЩИЕ ПРАВИЛА")
	w("• Работа должна быть оригинальной: не копируй чужие модели, иллюстрации, логотипы и узнаваемые дизайны существующих игр и фильмов.")
	w("• Никаких надписей с торговыми марками, реальных людей, политических и других запрещённых символов.")
	w("• Стиль единый для всей игры: холодная научная фантастика, тёмный космос, бирюзовые и фиолетовые акценты, чистые формы.")
	w("• Файл должен пройти проверку админки («Дизайн» → элемент → «Загрузить замену»): она сообщит об ошибках и предупреждениях.")
	w("• В ответе дай: готовый файл или чёткую инструкцию, как его получить, и короткий список того, что ты проверил по требованиям выше.")
	return b.String(), nil
}

func modelPrompt(b *strings.Builder, el Element) {
	w := func(format string, a ...any) { fmt.Fprintf(b, format+"\n", a...) }
	w("ЗАДАЧА: 3D-модель корабля «%s» (класс: %s), облик «%s».", shipName(el), orDash(el.Class), el.Skin)
	if el.Placeholder {
		w("Сейчас вместо неё стоит временная заглушка — модель «Стрижа». Нужна собственная модель этого корабля.")
	} else {
		w("Сейчас используется собственная модель; нужна улучшенная или новая версия в том же формате.")
	}
	w("")
	w("ФОРМАТ ФАЙЛА: .glb (glTF 2.0 binary), всё внутри одного файла: геометрия, материалы и текстуры. Внешних файлов и ссылок быть не должно.")
	w("• Нос корабля смотрит вдоль оси %s. Самая длинная ось модели — ось носа.", orDash(el.NoseAxis))
	w("• Длина модели около %.2f условных единиц (допускается 0,5–2 раза, но лучше точно). Центр модели — в начале координат, корабль симметричен относительно продольной плоскости.", el.ModelLength)
	w("• Не больше 40 000 треугольников (жёсткий предел 120 000), не больше 8 МБ файла.")
	w("• Материалы PBR (металличность и шероховатость), не больше 4 материалов; текстуры PNG или JPEG не больше 2048×2048, не больше 4 штук.")
	w("• Не использовать сжатие Draco и meshopt, расширения Basis, анимации, камеры, источники света. Нормали и масштаб применены (Apply Transform).")
	w("• Двигатели с отдельными соплами (точки выхлопа), оружейные точки на носу, место стыковки сзади или по ходу паспорта.")
	w("• Читаемый силуэт сверху и под углом 45° на маленьком экране телефона: крупные формы, без мелких деталей, которых не видно.")
	w("")
	w("ТОЧКИ ПРИВЯЗКИ. Вместе с моделью дай координаты в системе модели (x, y, z) для: Engine_L, Engine_R (сопла), Weapon_L, Weapon_R (стволы), Missile_01 (пусковая), Hit_Center, Camera_Focus, Dock_Point.")
	w("Оформи их как раздел \"points\" JSON из паспорта корабля (элемент «Паспорт внешнего вида»), чтобы эффекты в игре совпали с моделью.")
	w("")
	w("КАК ПРОВЕРИТЬ: открой GLB в просмотрщике glTF (например, Blender, https://gltf-viewer.donmccurdy.com), убедись, что нос смотрит по оси %s, длина соответствует, текстуры на месте, треугольников не больше лимита.", orDash(el.NoseAxis))
}

func iconPrompt(b *strings.Builder, el Element) {
	w := func(format string, a ...any) { fmt.Fprintf(b, format+"\n", a...) }
	w("ЗАДАЧА: иконка интерфейса «%s».", el.Name)
	w("")
	w("ФОРМАТ: SVG, viewBox=\"0 0 24 24\", один цвет через currentColor (игра сама красит иконку), линия 2 px со скруглёнными концами и стыками (stroke-linecap=round, stroke-linejoin=round), без заливок и градиентов, как набор Lucide.")
	w("• Без <script>, <image>, <foreignObject>, внешних ссылок, шрифтов и стилей через url(); только простые <path>, <circle>, <rect>, <line>, <polyline>.")
	w("• До 4 КБ, без обёрток и комментариев с лишними данными. Узнаваемо в размере 24 px и 48 px.")
	if el.PreviewSVG != "" {
		w("")
		w("ТЕКУЩАЯ ИКОНКА (сделай в том же стиле, но выразительнее или по новой идее):")
		w("%s", el.PreviewSVG)
	}
	w("")
	w("КАК ПРОВЕРИТЬ: открой SVG в браузере на тёмном фоне и в уменьшенном виде; убедись, что цвет задаётся currentColor.")
}

func backgroundPrompt(b *strings.Builder, el Element) {
	w := func(format string, a ...any) { fmt.Fprintf(b, format+"\n", a...) }
	w("ЗАДАЧА: слой фона космоса «%s».", el.Name)
	if len(el.Dims) == 2 {
		w("Сейчас: %d×%d пикселей.", el.Dims[0], el.Dims[1])
	}
	w("")
	w("ФОРМАТ: WebP, PNG или JPEG, не больше 4096 по стороне и 6 МБ; рекомендуется WebP около 1536×864 или 1672×941, 200–400 КБ.")
	w("• Фон накладывается слоями с параллаксом и аддитивным смешиванием: основа почти чёрная, яркими должны быть только звёзды и туманности, без ярких пятен по краям.")
	w("• Края должны стыковаться: слой повторяется зеркально (wrap mirror) — без швов, надписей и сильных виньеток.")
	w("• Палитра: глубокий синий и фиолетовый, бирюзовые акценты; без насыщенного красного и жёлтого. Читаемость корабля и подписей поверх фона важнее красоты.")
	w("")
	w("КАК ПРОВЕРИТЬ: положи слой на чёрный фон с режимом Screen или Add и убедись, что он не засвечивает центр и не даёт шва при зеркальном повторении.")
}

func shipDataPrompt(b *strings.Builder, el Element) {
	w := func(format string, a ...any) { fmt.Fprintf(b, format+"\n", a...) }
	w("ЗАДАЧА: паспорт внешнего вида корабля «%s» (JSON).", shipName(el))
	w("")
	w("ФОРМАТ: JSON-объект как в текущем паспорте. Обязательны: \"id\" (строго \"%s\"), \"skins\" (облики с полями name, glb, flame), \"points\" (точки привязки: Engine_L, Engine_R, Weapon_L, Weapon_R, Missile_01, Hit_Center, Camera_Focus, Dock_Point), \"model_length\", \"nose_axis\", \"visual_scale\", \"specs\".", el.Ship)
	w("• Координаты точек привязки — в системе координат 3D-модели корабля. После замены модели их нужно подогнать под новую геометрию.")
	w("• Пути glb оставь как в текущем паспорте: актуальную модель игра подставит из загруженных замен.")
	w("• Меняй только внешний вид, названия и подписи. Характеристики корабля (корпус, щит, скорость) здесь не хранятся.")
	w("")
	w("ТЕКУЩИЙ ПАСПОРТ (отредактируй и верни целиком, валидный JSON):")
	w("%s", el.Current)
}

func shipName(el Element) string {
	if i := strings.Index(el.Name, " — "); i > 0 {
		return el.Name[:i]
	}
	return strings.TrimPrefix(el.Name, "Паспорт внешнего вида: ")
}

func orDash(s string) string {
	if s == "" {
		return "—"
	}
	return s
}
