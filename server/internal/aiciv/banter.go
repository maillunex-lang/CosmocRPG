func tint(topic string, arch Archetype) []string {
	switch arch {
	case ArchNoob:
		switch topic {
		case "food":
			return []string{"а это можно есть во время полёта или меня отчитают?"}
		case "sleep":
			return []string{"я боюсь закрыть глаза, вдруг корабль сам уедет."}
		case "music":
			return []string{"а можно петь в эфир или это запрещено?"}
		default:
			return []string{"я не до конца понял, но мне интересно. объясните ещё раз, только проще."}
		}
	case ArchTroll:
		switch topic {
		case "food":
			return []string{"я вчера съел чей-то паёк. было вкусно. не благодарите."}
		case "pet":
			return []string{"кот у меня капитан. я так, на подхвате."}
		case "smack":
			return []string{"дань принята. жду чай. жду уже долго. это шутка."}
		default:
			return []string{"интересно. а теперь представьте, что это всё враньё."}
		}
	case ArchKnow:
		return []string{"если уж говорить точно, это чуть сложнее, чем вы рассказали."}
	case ArchDull:
		return []string{"а. ну. я слышал. нормально, наверно."}
	case ArchGrinder:
		return []string{"можно короче? у меня цикл, но я слушаю краем уха."}
	case ArchHelp:
		return []string{"если надо — я рядом, даже если разговор не про корабли."}
	default:
		return nil
	}
}
