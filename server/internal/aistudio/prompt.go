// BatchNote — описание партии для README и промпта.
func BatchNote(size, index, total int, ids []string) string {
	if len(ids) == 0 {
		return ""
	}
	return fmt.Sprintf("Партия %d из %d (по %d капитанов): %s — %s. Улучшай только этих капитанов.", index, total, size, ids[0], ids[len(ids)-1])
}
